    /// <summary>The short title for a status code; unknown codes get the generic one.</summary>
    public static string Title(int? status, string language) =>
        (language == English ? EnglishTitles : TurkishTitles).TryGetValue(status ?? 500, out var title)
            ? title
            : language == English ? "Error" : "Hata";

    /// <summary>The message for an error code with its arguments filled in; <c>null</c> for an unknown code.</summary>
    public static string? Detail(string code, string language, IReadOnlyDictionary<string, object?> arguments)
    {
        var messages = language == English ? EnglishMessages : TurkishMessages;
        return messages.TryGetValue(code, out var template)
            ? Placeholder().Replace(template, match =>
                arguments.TryGetValue(match.Groups[1].Value, out var value) && value is not null
                    ? Convert.ToString(value, CultureInfo.InvariantCulture) ?? match.Value
                    : match.Value)
            : null;
    }

    [GeneratedRegex(@"\{(\w+)\}", RegexOptions.CultureInvariant)]
    private static partial Regex Placeholder();
