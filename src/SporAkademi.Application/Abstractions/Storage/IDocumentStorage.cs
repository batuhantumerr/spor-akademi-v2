namespace SporAkademi.Application.Abstractions.Storage;

/// <summary>How a download link makes the browser treat the file.</summary>
/// <param name="ContentType">Served instead of anything stored with the object.</param>
/// <param name="FileName">Sanitised download name.</param>
/// <param name="Inline">Images are shown in the page; anything else is always a download (attachment).</param>
public sealed record DownloadDisposition(string ContentType, string FileName, bool Inline);

/// <summary>A short-lived, signed link to one private object (DEC-323).</summary>
public sealed record DownloadLink(Uri Url, DateTimeOffset ExpiresAt);

/// <summary>
/// Private object storage for documents (P2-F6). The provider is swappable (S3-compatible today, DEC-320):
/// the application only puts, deletes and asks for short-lived download links; the bucket is never public.
/// Keys are generated by the application and never contain user input.
/// </summary>
public interface IDocumentStorage
{
    Task PutAsync(string key, byte[] content, string contentType, CancellationToken cancellationToken);

    /// <summary>Deleting a missing object succeeds (idempotent).</summary>
    Task DeleteAsync(string key, CancellationToken cancellationToken);

    /// <summary>
    /// A signed GET link valid for the configured lifetime (5 minutes by default). It only grants reading this one
    /// object; callers authorise the user before asking for it.
    /// </summary>
    DownloadLink CreateDownloadLink(string key, DownloadDisposition disposition);
}
